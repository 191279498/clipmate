/**
 * 社交站文案的话题清理（v2.6.1）
 *
 * 用户 2026-10-29 要求：本页文案里的话题标签 `#ABC` 一律去掉井号，变成 `ABC`。
 * 追问后拍板：`#` **和** `[话题]` 标记一起去掉，且**所有社交站**都改。
 *
 * 为什么要处理两种形态（都是实测原文，不是推测）：
 *   1) 小红书一手数据 `desc` 长这样 —— `…#万万没想到[话题]# #沙发[话题]##少爷[话题]#`
 *      API 直接把 `[话题]` 三个字塞在话题名后面，而且话题紧邻时中间**没有空格**。
 *      只删 `#` 会得到 `万万没想到[话题] 沙发[话题]少爷[话题]`，等于没洗干净。
 *   2) 抖音 / 快手 / TikTok 的文案长这样 —— `…#送TA上精选 #抖音精选`
 *      没有 `[话题]`，就是一个 `#` 加名字。
 *
 * 处理顺序不能反：先啃「带 [话题] 的整块」（那是结构，能顺带补空格），
 * 再把剩下的裸 `#` 干掉。反过来先删 `#`，`[话题]` 块就散了，名字会粘在一起。
 *
 * 三条保命：
 *   · 幂等：同一段文字洗两遍结果一样（缓存命中会重复走一遍）。
 *   · 只动文案：非字符串、空值原样返回，不抛错、不返回 undefined。
 *   · 不跨行乱拼：换行原样保留，只压缩同一行里的多余空格。
 */
var SocialHashtagCleaner = {
  /** 小红书接口自带的话题后缀 */
  TAG_SUFFIX: /\[话题\]/g,

  /**
   * 清掉一段文案里的话题井号与 [话题] 标记
   *
   * @param {*} text - 原始文案（非字符串原样返回）
   * @returns {string} 清理后的文案
   */
  strip(text) {
    if (typeof text !== 'string' || !text) return text || '';
    // 没有 # 也没有 [话题]，一个字符都不用动（绝大多数非文案字段会走到这里）
    if (text.indexOf('#') < 0 && text.indexOf('[话题]') < 0) return text;

    let s = text;

    // ① 小红书形态：`#名称[话题]#` → `名称`，两侧补空格
    //    补空格是为了 `#沙发[话题]##少爷[话题]#` 这种紧邻的情况不粘连。
    //    `[^#\s]*?` 允许话题名是空的（`#[话题]#` 这种脏数据），此时只留空格。
    s = s.replace(/#([^#\s]*?)\[话题\]#?/g, ' $1 ');

    // ② 兜底：任何残留的 `[话题]`（例如 `#[话题]` 被上一步漏掉）一律当分隔
    s = s.replace(this.TAG_SUFFIX, ' ');

    // ③ 抖音/快手/TikTok 形态：裸 `#名称` → `名称`
    //    只删「后面紧跟非空白、非 #」的井号；行尾孤零零的 `#` 留着不动（那更像标点）。
    s = s.replace(/#(?=[^\s#])/g, '');

    // ④ 收尾：同一行内多余空格压成一个，去首尾空白（换行保持原样）
    s = s.replace(/[ \t]{2,}/g, ' ').replace(/[ \t]+\n/g, '\n').replace(/\n[ \t]+/g, '\n').trim();

    return s;
  },

  /**
   * 就地清理对象里的社交文案字段（`本页文案` / `本页标题` / 人物档案 `简介`）
   *
   * 标题也要清：标题是「昵称 + 文案前 20 字 + 日期」拼出来的，
   * 文案开头要是直接就是话题，标题里会带同一个 `#`。
   *
   * `简介` 是人物档案的签名（v2.7.15）：用户 2026-10-30 拍板「签名里的 #话题 不豁免」，
   * 走同一套规则。社交站没有 `简介` 这一列，加进来不会波及社交作品页。
   *
   * @param {Object} data - 字段表（会被就地修改）
   * @returns {Object} 同一个对象
   */
  stripFields(data) {
    if (!data || typeof data !== 'object') return data;
    ['本页文案', '本页标题', '简介'].forEach((key) => {
      if (typeof data[key] === 'string' && data[key]) {
        const cleaned = this.strip(data[key]);
        if (cleaned !== data[key]) data[key] = cleaned;
      }
    });
    return data;
  }
};

if (typeof module !== 'undefined' && module.exports) {
  module.exports = SocialHashtagCleaner;
}
